#!/usr/bin/env bash
#############################################################################
# workload_validation_jetty.sh - the workload validation of
# workload_validation.sh for Jetty, with a custom workload: the analyzed image
# serves static files, requested with Apache Bench (ab).
#
# (The docker-library official test for Jetty needs JSP support, which the
# analyzed image does not enable; see jetty_subject.conf.)
#
# Two containers are started for each phase:
#   server   the container under test: the analyzed image with its default
#            command, traced, and in the enforce phase run under the SysJava
#            policy. The static content is mounted read-only at webapps/ROOT;
#            the image itself is not modified.
#   client   helper (httpd image): runs ab against the server
# Only the server is in the traced cgroup; the client is neither traced nor
# confined (as the clients of the other scripts).
#
# Content: jetty_workload/ROOT/ (index.html), plus large.bin, a 1 MiB file of
# fixed bytes generated by this script. Load, in this order:
#   1. index.html, a new connection per request
#   2. index.html, keep-alive connections
#   3. large.bin
#
#   workload  the server under an allow-all seccomp filter while bpftrace
#             records its syscalls, binaries and libraries; then the diffs
#             against the SysJava policy and against SysJava's startup discovery.
#   enforce   the same with the server under the SysJava policy.
#
# Results go to the same folder and in the same layout as
# workload_validation.sh (subject: jetty, test: jetty-static-ab), so report.py
# and table.py cover it.
#
#   sudo env "PATH=$PATH" scripts/workload_validation/workload_validation_jetty.sh
#
# Environment (plus those of workload_validation.sh: PHASES, ARTIFACTS, OUT, ...):
#   SMALL_REQUESTS=500000       requests for index.html, new connection each (step 1)
#   KEEPALIVE_REQUESTS=3500000  requests for index.html over keep-alive connections (step 2)
#   LARGE_REQUESTS=85000        requests for large.bin (step 3)
#                             The defaults make each step last about 40 s on the test
#                             machine (measured: 13,800, 91,800 and 2,170 requests/s).
#   CONCURRENCY=16            concurrent connections
#   AB_IMAGE=httpd:2.4        image that provides ab
#   READY_TIMEOUT=300         seconds to wait for the server to start
#   RUN_TIMEOUT=1800          seconds allowed for one ab step
#   KEEP_FAILED=1             keep the server container of a failed run (for debugging)
#
# Requires: as workload_validation.sh, plus network access for the first run
# (the AB_IMAGE pull).
#############################################################################
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONF="${CONF:-$HERE/jetty_subject.conf}"
source "$HERE/wv_lib.sh"   # configuration, preflight, tracing, prepare_subject, postprocess
source "$CONF"             # SUBJECT, IMAGE, POLICY, READY_LOG, READY_PORT, WEBAPP_DIR

SMALL_REQUESTS="${SMALL_REQUESTS:-500000}"
KEEPALIVE_REQUESTS="${KEEPALIVE_REQUESTS:-3500000}"
LARGE_REQUESTS="${LARGE_REQUESTS:-85000}"
CONCURRENCY="${CONCURRENCY:-16}"
AB_IMAGE="${AB_IMAGE:-httpd:2.4}"
READY_TIMEOUT="${READY_TIMEOUT:-300}"
RUN_TIMEOUT="${RUN_TIMEOUT:-1800}"
TEST=jetty-static-ab
CONTENT_SRC="$HERE/jetty_workload/ROOT"
CONTENT="$ROOT/.cache/jetty-workload/ROOT"
LARGE_BYTES=1048576
SERVER=wv-jetty-server
CLIENT=wv-jetty-client

containers_down() { "$REAL_DOCKER" rm -vf "$CLIENT" "$SERVER" >/dev/null 2>&1; }
KEEP=0
jetty_cleanup() {
  (( KEEP )) || containers_down
  wv_cleanup
}
trap jetty_cleanup EXIT

# ------------------------------------------------------------------ content
[[ -f "$CONTENT_SRC/index.html" ]] || die "content not found: $CONTENT_SRC/index.html"
rm -rf "$CONTENT"; mkdir -p "$CONTENT"
cp -R "$CONTENT_SRC/." "$CONTENT/"
# large.bin: the byte values 0..255 repeated up to 1 MiB (the same file on every run)
"$PY" -c 'import sys; open(sys.argv[1], "wb").write(bytes(range(256)) * (int(sys.argv[2]) // 256))' \
  "$CONTENT/large.bin" "$LARGE_BYTES" || die "cannot generate large.bin"
chmod -R a+rX "$ROOT/.cache/jetty-workload"   # the server runs as the unprivileged user jetty
"$REAL_DOCKER" image inspect "$AB_IMAGE" >/dev/null 2>&1 \
  || "$REAL_DOCKER" pull -q "$AB_IMAGE" >/dev/null || die "cannot pull $AB_IMAGE"

RUN_META+="
content: index.html sha256 $(sha256sum "$CONTENT/index.html" | cut -c1-16), large.bin $LARGE_BYTES bytes sha256 $(sha256sum "$CONTENT/large.bin" | cut -c1-16)
load: ab ($AB_IMAGE, $("$REAL_DOCKER" run --rm "$AB_IMAGE" ab -V 2>/dev/null | head -1)) -c $CONCURRENCY; index.html x $SMALL_REQUESTS, index.html keep-alive x $KEEPALIVE_REQUESTS, large.bin x $LARGE_REQUESTS"
log "output: $OUT"

# ------------------------------------------------------------------ server
ip_of() { "$REAL_DOCKER" inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$1" 2>/dev/null; }

wait_ready() {  # container marker port -> 0 when the marker is logged and the port accepts connections
  local c=$1 marker=$2 port=$3 ip deadline=$(( SECONDS + READY_TIMEOUT ))
  while (( SECONDS < deadline )); do
    [[ "$("$REAL_DOCKER" inspect -f '{{.State.Running}}' "$c" 2>/dev/null)" == true ]] || return 1
    ip="$(ip_of "$c")"
    if "$REAL_DOCKER" logs "$c" 2>&1 | grep -a -q -F -- "$marker" \
       && "$PY" -c 'import socket,sys; socket.create_connection((sys.argv[1], int(sys.argv[2])), 3).close()' \
            "$ip" "$port" 2>/dev/null; then
      return 0
    fi
    sleep 2
  done
  return 1
}

serves() {  # url file -> 0 if the server returns exactly the file
  "$PY" -c '
import sys, urllib.request
body = urllib.request.urlopen(sys.argv[1], timeout=60).read()
sys.exit(0 if body == open(sys.argv[2], "rb").read() else 1)' "$1" "$2"
}

# ab_step label requests url [ab options...] ; ab output on stdout/stderr
# -> 0 if ab completed all requests and none failed or got a non-2xx response
ab_step() {
  local label=$1 n=$2 url=$3 out rc; shift 3
  echo "### $label: ab -n $n -c $CONCURRENCY $* $url"
  out="$(timeout "$RUN_TIMEOUT" "$REAL_DOCKER" run --rm --name "$CLIENT" "$AB_IMAGE" \
           ab -n "$n" -c "$CONCURRENCY" "$@" "$url" < /dev/null)"
  rc=$?
  printf '%s\n### exit code: %s\n' "$out" "$rc"
  (( rc == 0 )) || return 1
  grep -q -E "^Complete requests:[[:space:]]+$n\$" <<< "$out" || return 1
  grep -q -E '^Failed requests:[[:space:]]+0$' <<< "$out" || return 1
  ! grep -q '^Non-2xx responses' <<< "$out"
}

# run_load profile out_prefix -> prints the status
# Starts the server under the profile, runs the three ab steps, removes the server.
run_load() {
  local profile=$1 pre=$2 status=pass base
  : > "$pre.stdout"; : > "$pre.stderr"
  containers_down

  # the container under test: the analyzed image and command, plus the content
  "$REAL_DOCKER" run -d --name "$SERVER" --cgroup-parent "$CG_PARENT" --security-opt "seccomp=$profile" \
    -v "$CONTENT:$WEBAPP_DIR:ro" "$IMAGE" 2>> "$pre.stderr" | sed 's/^/cid /' > "$pre.injected"
  if ! wait_ready "$SERVER" "$READY_LOG" "$READY_PORT"; then
    status="fail(not-ready)"
  else
    base="http://$(ip_of "$SERVER"):$READY_PORT"
    if ! serves "$base/index.html" "$CONTENT/index.html" 2>> "$pre.stderr" \
       || ! serves "$base/large.bin" "$CONTENT/large.bin" 2>> "$pre.stderr"; then
      status="fail(content)"
    elif ! ab_step "index.html" "$SMALL_REQUESTS" "$base/index.html" >> "$pre.stdout" 2>> "$pre.stderr"; then
      status="fail(index.html)"
    elif ! ab_step "index.html keep-alive" "$KEEPALIVE_REQUESTS" "$base/index.html" -k >> "$pre.stdout" 2>> "$pre.stderr"; then
      status="fail(index.html keep-alive)"
    elif ! ab_step "large.bin" "$LARGE_REQUESTS" "$base/large.bin" >> "$pre.stdout" 2>> "$pre.stderr"; then
      status="fail(large.bin)"
    fi
  fi

  "$REAL_DOCKER" logs "$SERVER" > "$pre.server.log" 2>&1
  if [[ $status != pass && -n "${KEEP_FAILED:-}" ]]; then
    log "keeping the server container of the failed run: $SERVER"
  else
    # removed without a graceful stop, as the official tests do (docker rm -f)
    containers_down
  fi
  echo "$status"
}

# ------------------------------------------------------------------ main
log "==================== $SUBJECT ($IMAGE)"
if prepare_subject "$SUBJECT" "$IMAGE" "$POLICY" \
     "benchmark: custom, static files with ab; content mounted at $WEBAPP_DIR"; then
  t=$TEST
  if has_phase workload; then
    rm -f "$sd/$t.workload."*
    log "[$SUBJECT] $t: workload run (allow-all filter, tracing)"
    trace_start "$sd/$t.workload"
    wl="$(run_load "$ALLOW_ALL_PROFILE" "$sd/$t.workload")"
    trace_stop
    # run_load runs in a subshell: note here that it kept its container
    [[ $wl != pass && -n "${KEEP_FAILED:-}" ]] && KEEP=1
    echo "$wl" > "$sd/$t.workload.status"
    log "[$SUBJECT] $t: workload run -> $wl"
    postprocess "$sd/$t.workload"
  fi

  if has_phase enforce && (( ! KEEP )); then
    rm -f "$sd/$t.enforce."*
    log "[$SUBJECT] $t: enforce run (SysJava policy)"
    en="$(run_load "$sd/policy.json" "$sd/$t.enforce")"
    [[ $en != pass && -n "${KEEP_FAILED:-}" ]] && KEEP=1
    echo "$en" > "$sd/$t.enforce.status"
    log "[$SUBJECT] $t: enforce run -> $en"
  fi
fi

echo
"$PY" "$HERE/report.py" "$OUT"
